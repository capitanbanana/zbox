package redact

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

// ruleYAML mirrors a single entry of rdx's `.redaction_rules` file.
type ruleYAML struct {
	ID            string `yaml:"id"`
	Pattern       string `yaml:"pattern"`
	IsRegex       *bool  `yaml:"is_regex,omitempty"`
	Hashed        bool   `yaml:"hashed,omitempty"`
	HashExtractor string `yaml:"hash_extractor,omitempty"`
	Action        string `yaml:"action,omitempty"`
	Replacement   string `yaml:"replacement,omitempty"`
	Category      string `yaml:"category,omitempty"`
	Description   string `yaml:"description,omitempty"`
}

type rulesYAML struct {
	Rules []ruleYAML `yaml:"rules"`
}

// RulesFile renders the candidates as an rdx `.redaction_rules` document.
// Replacements are deterministic (they come from the legend seed), so the
// request bodies rdx builds keep stable prefixes and prompt caching survives.
func RulesFile(cfg Config) ([]byte, error) {
	doc := rulesYAML{Rules: []ruleYAML{}}
	for _, c := range cfg.Rules {
		doc.Rules = append(doc.Rules, rulesFor(c)...)
	}
	out, err := yaml.Marshal(doc)
	if err != nil {
		return nil, fmt.Errorf("render rules: %w", err)
	}
	header := "# Generated by zbox from the VM legend. Do not edit by hand:\n" +
		"# replacement values are stable only as long as this file is generated.\n"
	return append([]byte(header), out...), nil
}

// rulesFor expands one candidate into rdx rules. GitHub remotes need two
// patterns because the same account appears as `github.com:user` in ssh
// remotes and `github.com/user` in https URLs.
func rulesFor(c Candidate) []ruleYAML {
	if c.Hash != "" {
		return []ruleYAML{{
			ID:            "secret-" + c.Hash[:10],
			Pattern:       c.Hash,
			Hashed:        true,
			HashExtractor: c.Extractor,
			Category:      "KEY",
			Description:   "suspected credential " + c.Context,
		}}
	}
	value := strings.TrimSpace(c.Value)
	if value == "" {
		return nil
	}
	escaped := regexp.QuoteMeta(value)
	if host, owner, ok := strings.Cut(value, ":"); ok && strings.Contains(host, ".") && !strings.Contains(owner, "/") && c.Category == "HOST" {
		var out []ruleYAML
		for _, sep := range []string{":", "/"} {
			out = append(out, ruleYAML{
				ID:          ruleID(c.Category, value+sep),
				Pattern:     regexp.QuoteMeta(host + sep + owner),
				Replacement: c.Replacement,
				Category:    c.Category,
				Description: describe(c),
			})
		}
		return out
	}
	pattern := escaped
	switch c.Category {
	case "NAME", "HOST", "PROJECT", "PATH":
		if value != "/" {
			pattern = `\b` + escaped + `\b`
		}
	}
	return []ruleYAML{{
		ID:          ruleID(c.Category, value),
		Pattern:     pattern,
		Replacement: c.Replacement,
		Category:    c.Category,
		Description: describe(c),
	}}
}

func describe(c Candidate) string {
	parts := []string{"zbox"}
	if c.Source != "" {
		parts = append(parts, "source="+c.Source)
	}
	if c.Context != "" {
		parts = append(parts, c.Context)
	}
	return strings.Join(parts, " ")
}

// ruleID is stable for a (category, value) pair so regenerating the file does
// not churn ids.
func ruleID(category, value string) string {
	return strings.ToLower(category) + "-" + sha256Hex(value)[:10]
}

// WriteRulesFile writes the rules with owner-only permissions, replacing any
// previous file atomically so a half-written file can never be loaded.
func WriteRulesFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".redaction_rules.*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	defer os.Remove(name)
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(name, 0o600); err != nil {
		return err
	}
	return os.Rename(name, path)
}
